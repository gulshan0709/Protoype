// Assigns every demo person one pooled portrait, so each person keeps the same
// photo everywhere and no page shows two people with the same photo.
// Usage: node scripts/assign-demo-portraits.cjs [--check]
// Reads src/shared/people/portraitPool.json (id, gender, look), scans the demo
// data (scripts/lib/demo-people.cjs) and writes
//   src/shared/people/portraitAssignments.json  { "Kavita Rao": "sa-w-07", ... }
//   src/shared/ui/portraitImages.ts             static require()s for Metro
// --check exits 1 when either committed file is stale. Output is deterministic.
const fs = require("node:fs");
const path = require("node:path");
const { scanDemoPeople } = require("./lib/demo-people.cjs");
const { assignPortraits } = require("./lib/portrait-coloring.cjs");

const root = path.resolve(__dirname, "..");
const files = {
  pool: path.join(root, "src/shared/people/portraitPool.json"),
  assignments: path.join(root, "src/shared/people/portraitAssignments.json"),
  images: path.join(root, "src/shared/ui/portraitImages.ts"),
};

/** A committed file's text with LF line endings (git may check files out with CRLF). */
function current(file) {
  return fs.existsSync(file) ? fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n") : undefined;
}

function readPool() {
  return JSON.parse(fs.readFileSync(files.pool, "utf8")).map(({ id, gender, look }) => ({ id, gender, look }));
}

function imagesModule(pool) {
  const ids = pool.map((p) => p.id).sort();
  const lines = ids.map(
    (id) =>
      `  "${id}": {\n` +
      `    hd: require("../../../assets/profiles/people/${id}.jpg"),\n` +
      `    thumb: require("../../../assets/profiles/people/thumbs/${id}.jpg"),\n` +
      `  },`,
  );
  return [
    "// Generated by scripts/assign-demo-portraits.cjs from src/shared/people/portraitPool.json. Do not edit.",
    "// Metro needs literal require() paths: 1080×1080 HD portraits and 256×256 thumbnails.",
    "export const portraitImages: Record<string, { hd: number; thumb: number }> = {",
    ...lines,
    "};",
    "",
  ].join("\n");
}

/** Everything the script writes, plus the report. Pure apart from reading the data. */
function build() {
  const pool = readPool();
  const scan = scanDemoPeople();
  const result = assignPortraits(pool, scan.persons, scan.pages);
  return {
    pool,
    scan,
    result,
    outputs: {
      [files.assignments]: JSON.stringify(result.assignments, null, 2) + "\n",
      [files.images]: imagesModule(pool),
    },
  };
}

function report({ scan, result }) {
  const perIndustry = {};
  const unclassified = [];
  for (const [name, p] of scan.persons) {
    if (!p.gender) unclassified.push(name);
    for (const industry of p.industries) {
      const e = (perIndustry[industry] ??= { people: 0, withPortrait: 0 });
      e.people++;
      if (p.gender) e.withPortrait++;
    }
  }
  const lines = [
    `Scanned ${scan.pageCount} pages, ${scan.sessionCount} class/lab sessions: ${scan.persons.size} people, ${Object.keys(result.assignments).length} assigned.`,
    "People per industry: " +
      Object.entries(perIndustry)
        .map(([k, v]) => `${k} ${v.people} (${v.withPortrait} with portrait)`)
        .join(", "),
    "Groups: " +
      Object.entries(result.groups)
        .map(([k, g]) => `${k} ${g.people} people, ${g.coloursUsed}/${g.pool} portraits, max ${g.maxOnPage} on a page`)
        .join("; "),
  ];
  if (unclassified.length)
    lines.push(`Initials only (no gender): ${unclassified.length} — ${unclassified.sort().join(", ")}`);
  if (result.overfull.length) {
    lines.push(`Pages with more people than portraits (${result.overfull.length}, least-conflicting ids used):`);
    for (const o of result.overfull)
      lines.push(
        `  ${o.page} [${o.group}] ${o.people} people / ${o.pool} portraits, ${o.repeats} repeats (minimum ${o.minimum})`,
      );
  }
  if (result.conflicts.length) {
    lines.push(`Pages left with repeated portraits (${result.conflicts.length}):`);
    for (const o of result.conflicts) lines.push(`  ${o.page} [${o.group}] ${o.people} people, ${o.repeats} repeats`);
  }
  return lines.join("\n");
}

function main() {
  const check = process.argv.includes("--check");
  const built = build();
  const stale = Object.entries(built.outputs).filter(([file, text]) => current(file) !== text);
  if (check) {
    if (stale.length) {
      for (const [file] of stale) console.error("Stale: " + path.relative(root, file));
      console.error("Run `npm run portraits:assign` to regenerate.");
      process.exit(1);
    }
    console.log("Portrait assignments are up to date.");
    return;
  }
  for (const [file, text] of stale) fs.writeFileSync(file, text);
  console.log(report(built));
  console.log(stale.length ? "Wrote " + stale.map(([f]) => path.relative(root, f)).join(", ") : "No changes.");
}

if (require.main === module) main();
module.exports = { build, report, files, current };
