// Regenerate the Media Explorer frame pool from the bundled demo media (see assets/media/README.md).
// Usage: node scripts/prepare-media-frames.cjs <ffmpeg executable>
// Reads assets/media/gate-*.mp4 and still-*.jpg (nothing is downloaded) and writes:
//   assets/media/frames/clip<n>-<ii>.jpg   1280x720 frames, 2 per second of each clip
//   assets/media/frames/thumbs/*.jpg       480x270 grid thumbnails (clip frames and stills)
//   src/domain/media/framePool.json        scenes: which frames a camera shows, in order, with sizes
//   src/features/workspace/components/mediaFrameSources.ts  bundled sources for each frame file
const fs = require("node:fs");
const path = require("node:path");
const { runner } = require("./lib/ffmpeg.cjs");
const [ffmpeg] = process.argv.slice(2);
if (!ffmpeg) throw new Error("Provide an ffmpeg executable");
const root = path.resolve(__dirname, "..");
const media = path.join(root, "assets/media");
const out = path.join(media, "frames");
const thumbs = path.join(out, "thumbs");
fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(thumbs, { recursive: true });
const run = runner(ffmpeg);
const FPS = 2;
const CLIP_FRAMES = 16; // 8 s clips at 2 fps
// Each clip already carries its tracking boxes, so its frames are drawn as they are.
for (const clip of [1, 2, 3]) {
  const source = path.join(media, `gate-${clip}.mp4`);
  run([
    "-i",
    source,
    "-vf",
    `fps=${FPS},scale=1280:720`,
    "-frames:v",
    String(CLIP_FRAMES),
    "-q:v",
    "4",
    path.join(out, `clip${clip}-%02d.jpg`),
  ]);
  run([
    "-i",
    source,
    "-vf",
    `fps=${FPS},scale=480:270`,
    "-frames:v",
    String(CLIP_FRAMES),
    "-q:v",
    "5",
    path.join(thumbs, `clip${clip}-%02d.jpg`),
  ]);
}
// Stills (from prepare-demo-captures.cjs) are reused at full size; only a grid
// thumbnail is added. The UI draws their box.
const stills = fs
  .readdirSync(media)
  .map((file) => /^still-(\w+)\.jpg$/.exec(file)?.[1])
  .filter(Boolean);
for (const id of stills)
  run([
    "-i",
    path.join(media, `still-${id}.jpg`),
    "-vf",
    "scale=480:270",
    "-q:v",
    "5",
    path.join(thumbs, `still-${id}.jpg`),
  ]);

const size = (file) => fs.statSync(file).size;
const clipScene = (clip) => ({
  burst: CLIP_FRAMES,
  interval: 1 / FPS,
  frames: Array.from({ length: CLIP_FRAMES }, (_, i) => {
    const file = `clip${clip}-${String(i + 1).padStart(2, "0")}`;
    return { file, size: size(path.join(out, file + ".jpg")) };
  }),
  // The slot's recording plays gate-<clip>.mp4 (videoAsset index clip - 1).
  recording: {
    video: clip - 1,
    size: size(path.join(media, `gate-${clip}.mp4`)),
  },
});
const stillScene = (ids, interval) => ({
  burst: ids.length,
  interval,
  frames: ids.map((id) => ({
    file: `still-${id}`,
    still: id,
    size: size(path.join(media, `still-${id}.jpg`)),
  })),
});
// Scenes group frames of one place. See assets/media/README.md for what each source shows.
const pool = {
  "corridor-a": clipScene(1),
  "corridor-b": clipScene(2),
  "corridor-c": clipScene(3),
  hall: stillScene(["w1", "w2", "w3", "w4", "w5", "w6", "w7"], 1.5),
  lobby: stillScene(["m1", "w8", "m2", "m7"], 2),
  classroom: stillScene(["m4", "m5", "m6"], 4),
  library: stillScene(["m3"], 3),
};
fs.mkdirSync(path.join(root, "src/domain/media"), { recursive: true });
// One frame per line keeps the generated pool readable in review.
const json = JSON.stringify(pool, null, 1).replace(
  /\{\n\s+"file": ([^\n]+)\n(\s+"[^\n]+\n)*?\s+\}/g,
  (block) => block.replace(/\n\s*/g, " ").replace("{ ", "{").replace(" }", "}"),
);
fs.writeFileSync(
  path.join(root, "src/domain/media/framePool.json"),
  json + "\n",
);

const files = [
  ...new Set(
    Object.values(pool).flatMap((scene) => scene.frames.map((f) => f.file)),
  ),
];
const rel = "../../../../assets/media";
const lines = files.map((file) => {
  const full = file.startsWith("still-")
    ? `${rel}/${file}.jpg`
    : `${rel}/frames/${file}.jpg`;
  return `  "${file}": { full: require("${full}"), thumb: require("${rel}/frames/thumbs/${file}.jpg") },`;
});
fs.writeFileSync(
  path.join(root, "src/features/workspace/components/mediaFrameSources.ts"),
  `// Generated by scripts/prepare-media-frames.cjs. Bundled Media Explorer frames.
// Keys match the "file" of each frame in src/domain/media/framePool.json.
export const mediaFrameSources: Record<string, { full: number; thumb: number }> = {
${lines.join("\n")}
};
`,
);
const total = files.reduce(
  (sum, file) =>
    sum +
    size(path.join(thumbs, file + ".jpg")) +
    (file.startsWith("still-") ? 0 : size(path.join(out, file + ".jpg"))),
  0,
);
console.log(
  `${files.length} frame files, ${(total / 1024 / 1024).toFixed(2)} MB added`,
);
